// Hunter armour sets by quality and the bows from Warcry_archers.zip (body parts per race and rarity).
// Unzips into a temp folder and copies the models into public/assets/models/archers/ under flat names:
//   <race>_archer_<part>_<rarity>.fbx, bow_<rarity>.fbx (variant_new), bow_<rarity>_v1.fbx (variant_similar).
// The parts' own textures are external, `<model>.fbm/<name>_baked`: any found in the zip are converted to
// public/assets/textures/archers/<name>_baked.png (macOS `sips`) and listed in src/archerTextures.ts, so the game
// asks only for textures that exist (src/assets.ts).
// Usage: node tools/import-archers.mjs [/path/to/Warcry_archers_fbm.zip]
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ZIP = process.argv[2] ?? '/Users/gr/Desktop/Warcry_archers_fbm.zip';
const OUT = join(ROOT, 'public/assets/models/archers');
const TEX = join(ROOT, 'public/assets/textures/archers');
const RACES = ['human', 'orc'];
const PARTS = ['head', 'torso', 'arms', 'legs'];
/** Same order as config RARITY. */
const RARITIES = ['common', 'uncommon', 'rare', 'epic', 'legendary', 'mythic'];

const tmp = mkdtempSync(join(tmpdir(), 'archers-'));
execFileSync('unzip', ['-q', ZIP, '-d', tmp]);
const SRC = join(tmp, 'Warcry_archers');
mkdirSync(OUT, { recursive: true });
mkdirSync(TEX, { recursive: true });

let n = 0, missing = 0;
const copy = (rel, name) => {
  const src = join(SRC, rel);
  if (!existsSync(src)) { console.warn('missing', rel); missing++; return; }
  copyFileSync(src, join(OUT, `${name}.fbx`));
  n++;
};
for (const race of RACES) {
  for (const part of PARTS) {
    for (const r of RARITIES) copy(`${race}/${part}/${race}_archer_${part}_${r}.fbx`, `${race}_archer_${part}_${r}`);
  }
}
copy('bows/bow_common.fbx', 'bow_common');
for (const r of RARITIES.slice(1)) {
  copy(`bows/variant_new/bow_${r}.fbx`, `bow_${r}`);
  copy(`bows/variant_similar/bow_${r}_v1.fbx`, `bow_${r}_v1`);
}

// baked textures in any *.fbm folder (with or without an image extension)
const textures = [];
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (basename(dir).endsWith('.fbm')) {
      const name = basename(f, extname(f));
      // only the parts' own textures: the race atlas copies (human_albedo / orc_albedo) are in the game already
      if (!name.endsWith('_baked')) continue;
      execFileSync('sips', ['-s', 'format', 'png', '-Z', '1024', p, '--out', join(TEX, `${name}.png`)], { stdio: 'ignore' });
      textures.push(name);
    }
  }
};
walk(SRC);
writeFileSync(join(ROOT, 'src/archerTextures.ts'),
  '// Generated by tools/import-archers.mjs: baked textures of the hunter sets present in public/assets/textures/archers.\n' +
  `export const ARCHER_TEXTURES = new Set<string>(${JSON.stringify([...new Set(textures)].sort(), null, 2)});\n`);
rmSync(tmp, { recursive: true, force: true });
console.log(`models: ${n}, textures: ${textures.length}, missing: ${missing}`);
